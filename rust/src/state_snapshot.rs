#[cfg(test)]
mod tests {
    use super::*;
    use crate::state::pad_label_32;

    fn reset() {
        TOKEN_STORE.with(|ts| ts.borrow_mut().clear());
        OBJECTS.with(|o| o.borrow_mut().clear());
    }

    fn sample_token(slot: u32) -> TokenState {
        TokenState {
            slot_id: slot,
            initialized: true,
            label: pad_label_32("snap-test"),
            login_state: LoginState::User, // must NOT survive the round-trip
            so_pin_salt: [7u8; 16],
            so_pin_hash: [8u8; 32],
            user_pin_salt: Some([9u8; 16]),
            user_pin_hash: Some([10u8; 32]),
        }
    }

    #[test]
    fn round_trip_restores_tokens_and_token_objects_only() {
        // The crate-wide lock, NOT a private one: these tests clear the
        // global OBJECTS / TOKEN_STORE, which every `native::*` test also
        // depends on (see native::mod::test_lock's own doc comment).
        let _g = crate::native::test_lock::acquire();
        reset();
        TOKEN_STORE.with(|ts| {
            ts.borrow_mut().insert(0, sample_token(0));
        });
        let mut token_obj: Attributes = HashMap::new();
        token_obj.insert(CKA_TOKEN, vec![1]);
        token_obj.insert(CKA_VALUE, vec![1, 2, 3, 4]);
        let mut session_obj: Attributes = HashMap::new();
        session_obj.insert(CKA_TOKEN, vec![0]);
        session_obj.insert(CKA_VALUE, vec![9, 9]);
        OBJECTS.with(|o| {
            let mut s = o.borrow_mut();
            s.insert(200, token_obj.clone());
            s.insert(201, session_obj);
        });

        let blob = serialize_token_state();
        reset();
        deserialize_token_state(&blob).expect("round trip");

        TOKEN_STORE.with(|ts| {
            let s = ts.borrow();
            let t = s.get(&0).expect("token restored");
            assert!(t.initialized);
            assert_eq!(t.label, pad_label_32("snap-test"));
            assert_eq!(t.user_pin_hash, Some([10u8; 32]));
            // Sessions are gone — login state resets.
            assert!(matches!(t.login_state, LoginState::Public));
        });
        OBJECTS.with(|o| {
            let s = o.borrow();
            assert_eq!(s.get(&200), Some(&token_obj), "token object restored");
            assert!(
                !s.contains_key(&201),
                "session object must not survive the snapshot"
            );
        });
    }

    #[test]
    fn truncated_snapshot_is_rejected_and_state_untouched() {
        // The crate-wide lock, NOT a private one: these tests clear the
        // global OBJECTS / TOKEN_STORE, which every `native::*` test also
        // depends on (see native::mod::test_lock's own doc comment).
        let _g = crate::native::test_lock::acquire();
        reset();
        TOKEN_STORE.with(|ts| {
            ts.borrow_mut().insert(0, sample_token(0));
        });
        let blob = serialize_token_state();

        // Pre-load some live state that a failed load must not disturb.
        reset();
        TOKEN_STORE.with(|ts| {
            ts.borrow_mut().insert(3, sample_token(3));
        });

        for cut in [0, 4, 9, blob.len() - 1] {
            assert!(
                deserialize_token_state(&blob[..cut]).is_err(),
                "truncation at {cut} must fail"
            );
        }
        assert!(
            deserialize_token_state(b"XXXXXXXXjunkjunkjunk").is_err(),
            "bad magic must fail"
        );
        TOKEN_STORE.with(|ts| {
            assert!(ts.borrow().contains_key(&3), "failed load must not wipe state");
        });
    }
}
