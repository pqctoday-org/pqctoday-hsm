//! Token-state snapshot / restore — the persistence surface for the
//! wasm32-unknown-emscripten staticlib embedding (openssl.wasm).
//!
//! Why this exists: this engine keeps ALL state in memory (`state.rs`
//! lazy_statics). That is fine for the wasm-bindgen playground (one module
//! instance per page) and the native KMIP server (one long-lived process),
//! but openssl.wasm is built with `-sEXIT_RUNTIME=1`: every `callMain()`
//! tears the runtime down, and pkcs11-provider's teardown calls
//! `C_Finalize`, which zeroizes and wipes the object store. Without a
//! snapshot taken BEFORE that wipe, a token key generated by one CLI
//! command simply does not exist for the next one — the exact failure mode
//! the C++ engine avoided with its file-backed token directory (see
//! openssl-studio-pkcs11-wiring-plan-07242026.md WP1/WP3).
//!
//! Scope of a snapshot (PKCS#11 semantics: what a real token's nonvolatile
//! storage would hold):
//!   - `TOKEN_STORE` (slot/token metadata, PIN hashes; `login_state` is
//!     always restored as `Public` — sessions do not survive finalize)
//!   - objects in `OBJECTS` with `CKA_TOKEN = TRUE` (session objects die
//!     with the session per §4.4)
//!   - `NEXT_HANDLE` / `UNIQUE_ID_COUNTER` (so rehydrated handles can
//!     never collide with newly created ones)
//!
//! Format: versioned little-endian binary, magic `SHR3SNP1`. Hand-rolled
//! (no serde dependency) — the shapes are three flat maps of bytes.

use std::collections::HashMap;

use crate::constants::*;
use crate::crypto::handlers::Attributes;
use crate::state::{
    LoginState, TokenState, NEXT_HANDLE, OBJECTS, TOKEN_STORE, UNIQUE_ID_COUNTER,
};

/// Snapshot format magic. Bumped `SHR3SNP1` → `SHR3SNP2` on 2026-08-13 by
/// remediation item S4: the stateful HBS attribute ids MOVED out of the
/// client-writable vendor range into the engine-private one. A snapshot
/// written under the old layout carries the leaf index and serialised
/// one-time-signature state under ids this build no longer reads, so the
/// counters would come back ABSENT — presenting a partially used XMSS/LMS key
/// as a fresh one, which is precisely the rewind the item exists to prevent.
///
/// The decision (taken before implementation, not discovered here) is to
/// REFUSE such snapshots loudly rather than migrate them in place: a
/// silently reinterpreted stateful key is a forgery risk, an explicit load
/// failure is an operations problem. Anyone implementing KMIP engine-key
/// persistence must read this first.
const MAGIC: &[u8; 8] = b"SHR3SNP2";

/// The superseded pre-S4 magic — recognised only so the loader can return a
/// specific error instead of a generic parse failure.
const MAGIC_V1: &[u8; 8] = b"SHR3SNP1";

// ─────────────────────────────────────────────────────────────────────────
// Serialize
// ─────────────────────────────────────────────────────────────────────────

fn put_u32(out: &mut Vec<u8>, v: u32) {
    out.extend_from_slice(&v.to_le_bytes());
}
fn put_u64(out: &mut Vec<u8>, v: u64) {
    out.extend_from_slice(&v.to_le_bytes());
}

/// Serialize the persistent slice of engine state. Always succeeds; an
/// empty engine produces a valid (small) snapshot.
pub fn serialize_token_state() -> Vec<u8> {
    let mut out = Vec::with_capacity(4096);
    out.extend_from_slice(MAGIC);
    put_u32(
        &mut out,
        NEXT_HANDLE.load(std::sync::atomic::Ordering::Relaxed),
    );
    put_u64(
        &mut out,
        UNIQUE_ID_COUNTER.load(std::sync::atomic::Ordering::Relaxed),
    );

    TOKEN_STORE.with(|ts| {
        let store = ts.borrow();
        put_u32(&mut out, store.len() as u32);
        // Deterministic order (BTreeMap-like) so identical state → identical bytes.
        let mut slots: Vec<&u32> = store.keys().collect();
        slots.sort();
        for slot in slots {
            let t = &store[slot];
            put_u32(&mut out, t.slot_id);
            out.push(t.initialized as u8);
            out.extend_from_slice(&t.label);
            out.extend_from_slice(&t.so_pin_salt);
            out.extend_from_slice(&t.so_pin_hash);
            match (&t.user_pin_salt, &t.user_pin_hash) {
                (Some(salt), Some(hash)) => {
                    out.push(1);
                    out.extend_from_slice(salt);
                    out.extend_from_slice(hash);
                }
                _ => out.push(0),
            }
        }
    });

    OBJECTS.with(|o| {
        let store = o.borrow();
        let token_objects: Vec<(&u32, &Attributes)> = {
            let mut v: Vec<(&u32, &Attributes)> = store
                .iter()
                .filter(|(_, attrs)| {
                    attrs
                        .get(&CKA_TOKEN)
                        .map(|v| v.first() == Some(&1))
                        .unwrap_or(false)
                })
                .collect();
            v.sort_by_key(|(h, _)| **h);
            v
        };
        put_u32(&mut out, token_objects.len() as u32);
        for (handle, attrs) in token_objects {
            put_u32(&mut out, *handle);
            put_u32(&mut out, attrs.len() as u32);
            let mut types: Vec<&u32> = attrs.keys().collect();
            types.sort();
            for ty in types {
                let val = &attrs[ty];
                put_u32(&mut out, *ty);
                put_u32(&mut out, val.len() as u32);
                out.extend_from_slice(val);
            }
        }
    });

    out
}

// ─────────────────────────────────────────────────────────────────────────
// Deserialize
// ─────────────────────────────────────────────────────────────────────────

struct Cursor<'a> {
    buf: &'a [u8],
    pos: usize,
}

impl<'a> Cursor<'a> {
    fn take(&mut self, n: usize) -> Result<&'a [u8], u32> {
        if self.pos + n > self.buf.len() {
            return Err(CKR_GENERAL_ERROR);
        }
        let s = &self.buf[self.pos..self.pos + n];
        self.pos += n;
        Ok(s)
    }
    fn u8(&mut self) -> Result<u8, u32> {
        Ok(self.take(1)?[0])
    }
    fn u32(&mut self) -> Result<u32, u32> {
        Ok(u32::from_le_bytes(self.take(4)?.try_into().unwrap()))
    }
    fn u64(&mut self) -> Result<u64, u32> {
        Ok(u64::from_le_bytes(self.take(8)?.try_into().unwrap()))
    }
}

/// Parse and install a snapshot produced by [`serialize_token_state`].
///
/// Fully parses into temporaries BEFORE touching engine state — a truncated
/// or corrupt snapshot returns `CKR_GENERAL_ERROR` and leaves the engine
/// untouched. On success, replaces `TOKEN_STORE` and the token objects in
/// `OBJECTS` (session objects and operation state are untouched — callers
/// load snapshots at module boot when those are empty anyway), and bumps
/// the counters to at least their snapshot values.
pub fn deserialize_token_state(buf: &[u8]) -> Result<(), u32> {
    let mut c = Cursor { buf, pos: 0 };
    let magic = c.take(8)?;
    if magic == MAGIC_V1 {
        // S4 — old layout: refuse, do not reinterpret. See MAGIC.
        return Err(CKR_PQCTODAY_SNAPSHOT_FORMAT_UNSUPPORTED);
    }
    if magic != MAGIC {
        return Err(CKR_GENERAL_ERROR);
    }
    let next_handle = c.u32()?;
    let unique_id = c.u64()?;

    let token_count = c.u32()?;
    let mut tokens: HashMap<u32, TokenState> = HashMap::new();
    for _ in 0..token_count {
        let slot_id = c.u32()?;
        let initialized = c.u8()? != 0;
        let label: [u8; 32] = c.take(32)?.try_into().unwrap();
        let so_pin_salt: [u8; 16] = c.take(16)?.try_into().unwrap();
        let so_pin_hash: [u8; 32] = c.take(32)?.try_into().unwrap();
        let (user_pin_salt, user_pin_hash) = if c.u8()? != 0 {
            (
                Some(c.take(16)?.try_into().unwrap()),
                Some(c.take(32)?.try_into().unwrap()),
            )
        } else {
            (None, None)
        };
        tokens.insert(
            slot_id,
            TokenState {
                slot_id,
                initialized,
                label,
                login_state: LoginState::Public,
                so_pin_salt,
                so_pin_hash,
                user_pin_salt,
                user_pin_hash,
            },
        );
    }

    let obj_count = c.u32()?;
    let mut objects: HashMap<u32, Attributes> = HashMap::new();
    for _ in 0..obj_count {
        let handle = c.u32()?;
        let attr_count = c.u32()?;
        let mut attrs: Attributes = HashMap::with_capacity(attr_count as usize);
        for _ in 0..attr_count {
            let ty = c.u32()?;
            let len = c.u32()? as usize;
            attrs.insert(ty, c.take(len)?.to_vec());
        }
        objects.insert(handle, attrs);
    }

    // Commit.
    TOKEN_STORE.with(|ts| *ts.borrow_mut() = tokens);
    OBJECTS.with(|o| {
        let mut store = o.borrow_mut();
        // Drop any stale token objects (a load REPLACES nonvolatile storage),
        // keep session objects (none exist at the intended call point).
        store.retain(|_, attrs| {
            !attrs
                .get(&CKA_TOKEN)
                .map(|v| v.first() == Some(&1))
                .unwrap_or(false)
        });
        store.extend(objects);
    });
    let bump = |atomic: &std::sync::atomic::AtomicU32, v: u32| {
        atomic.fetch_max(v, std::sync::atomic::Ordering::Relaxed);
    };
    bump(&NEXT_HANDLE, next_handle);
    UNIQUE_ID_COUNTER.fetch_max(unique_id, std::sync::atomic::Ordering::Relaxed);
    Ok(())
}

