//! CKKS key rotation without decryption (E10; pqctoday-fhe
//! `docs/ckks/ckks-threshold-and-rotation-study-2026-10-11.md` §5, plan §3.4).
//!
//! The token streams one key-switching key from an old seed's secret to a new
//! seed's secret, at the residual levels that stored ciphertexts use. The FHE
//! server applies it to each stored ciphertext (Lattigo
//! `rlwe.Evaluator.ApplyEvaluationKey`); the result decrypts under the new
//! secret and no plaintext appears.
//!
//! `CKM_PQCTODAY_FHE_DERIVE_PUBLIC`, parameter version 3 (no new function or
//! codepoint). The two seeds are named by lineage (`CKA_PQCTODAY_FHE_LINEAGE_ID`,
//! readable by their user), and `hBaseKey` is `CK_INVALID_HANDLE`: an SO
//! session cannot find private objects, and handles to private token objects
//! are re-keyed at every logout (S6), so an SO never holds a seed handle.
//!
//! ```c
//! typedef struct CK_PQCTODAY_FHE_DERIVE_PUBLIC_PARAMS_V3 {
//!     CK_ULONG ulVersion;      /* 3 */
//!     CK_ULONG ulPublicKind;   /* 3 rotation descriptor, 5 rotation-key chunk, 6 rotation manifest */
//!     CK_ULONG ulKeyIndex;     /* 0 (one key) */
//!     CK_ULONG ulDigit;        /* kind 5: gadget digit */
//!     CK_ULONG ulLimbFrom;     /* kind 5: first limb */
//!     CK_ULONG ulLimbTo;       /* kind 5: one past the last limb */
//!     CK_BYTE  oldLineage[32]; /* the seed whose secret the key switches away from */
//!     CK_BYTE  newLineage[32]; /* the seed whose secret the key switches to */
//! } CK_PQCTODAY_FHE_DERIVE_PUBLIC_PARAMS_V3;
//! ```
//!
//! Rules (owner decisions 2026-10-11), checked on every call before any work:
//! * The session is an SO R/W session (`CKR_USER_NOT_LOGGED_IN` for a public
//!   session, `CKR_USER_TYPE_INVALID` for a user session). The SO reaches the
//!   two private seed objects through `fhe_custody::so_seed_by_lineage` only.
//! * Two distinct seed objects on the slot (`CKR_MECHANISM_PARAM_INVALID` for
//!   one lineage twice; `CKR_KEY_HANDLE_INVALID` when a lineage names no seed
//!   or more than one), both streamed-CKKS seeds that allow
//!   `CKM_PQCTODAY_FHE_DERIVE_PUBLIC`, with the same parameter set
//!   (`CKR_KEY_TYPE_INCONSISTENT`) and different seed values and lineages.
//! * The new seed was generated by this token: `CKA_LOCAL` = true and
//!   `CKA_KEY_GEN_MECHANISM` = `CKM_PQCTODAY_FHE_KEY_GEN`. An imported or
//!   replicated seed is refused, so a caller can never name a secret it knows
//!   as the target (holding s_new and the rotation key reveals s_old).
//! * The new seed's decryption policy is equal to or stricter than the old
//!   one's (the replication rule): rotation never widens what may be released.
//! * One direction, one target: a seed that has been rotated away from can
//!   never be a rotation target (refuses old → new → old), and a seed rotates
//!   to one target only (refuses a second, different target).
//!   Every refusal in this list is `CKR_KEY_FUNCTION_NOT_PERMITTED`.
//!
//! Kind 3 returns a DER `CkksRotationDescriptorV1` and starts (or restarts)
//! the session's rotation ledger; it also records the rotation on the old
//! seed (`CKA_PRIV_FHE_ROTATION` = new lineage ‖ 0x00). Kind 5 returns b limbs
//! [from, to) of digit d of the one key (key index 0), in the shape of the
//! version 2 evaluation-key chunks. Kind 6 returns a DER
//! `CkksSignedRotationManifestV1` signed by the device's receipt-signing key,
//! only when the ledger covers every digit exactly once, then marks the old
//! seed as rotated (state byte 0x01) and clears the ledger:
//!
//! ```text
//! CkksRotationDescriptorV1 ::= SEQUENCE { generatorVersion INTEGER (1),
//!     paramSet INTEGER, paramHash OCTET STRING,
//!     oldDescriptorHash OCTET STRING (SIZE(32)), newDescriptorHash OCTET STRING (SIZE(32)),
//!     oldLineage OCTET STRING, newLineage OCTET STRING,
//!     keyId OCTET STRING (SIZE(17)), aSeed OCTET STRING (SIZE(32)),
//!     digits INTEGER, limbs INTEGER }
//! CkksRotationManifestTbsV1 ::= SEQUENCE { version INTEGER (1),
//!     rotationDescriptorHash OCTET STRING (SIZE(32)),
//!     oldDescriptorHash OCTET STRING, newDescriptorHash OCTET STRING,
//!     paramHash OCTET STRING, oldLineage OCTET STRING, newLineage OCTET STRING,
//!     entries SEQUENCE OF CkksChunkHash }
//! CkksSignedRotationManifestV1 ::= SEQUENCE { tbs CkksRotationManifestTbsV1,
//!     signature OCTET STRING, signerChain SEQUENCE OF Certificate }
//! signed bytes = "PQCToday CKKS Rotation Manifest 1.0" || 0x00 || DER(tbs)
//! ```
//!
//! A descriptor hash is SHA-256 of the seed's version 2 kind 3 output
//! (`CkksKeySetDescriptorV1`), so both lineages and a-seeds are bound into
//! the rotation key's KDF contexts and its a-seed.
//!
//! Retiring the old seed (owner rule: destroyed once re-encryption is
//! confirmed): the confirmation is the SO's own act. After the FHE server
//! reports that every stored ciphertext was switched, the SO calls
//! `retire_old_seed(so_session, old_lineage)`, an SO operation like the policy
//! enrollments (an SO cannot name the private seed in `C_DestroyObject`). It
//! destroys the old seed only when its rotation manifest was signed (state
//! byte 0x01), clears the generator cache and every ledger that names it, and
//! logs `fhe_ckks_rotation_old_seed_destroyed` with both lineages. The token
//! cannot verify the server's re-encryption itself; no further protocol is
//! added. The seed's user can still destroy it with `C_DestroyObject` as
//! before.

