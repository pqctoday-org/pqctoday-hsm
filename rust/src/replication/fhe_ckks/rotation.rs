/// Domain separator of the rotation manifest; never equal to the key-set one.
pub const ROTATION_MANIFEST_DOMAIN: &[u8] = b"PQCToday CKKS Rotation Manifest 1.0";

/// Engine-private rotation record on the OLD seed: new lineage (32 bytes) ‖
/// state (0x00 rotation started, 0x01 rotation manifest signed). Never
/// client-writable (engine-private range).
pub const CKA_PRIV_FHE_ROTATION: u32 = 0xFFFF_000D;
const ROTATION_STARTED: u8 = 0;
const ROTATION_SIGNED: u8 = 1;

#[derive(Clone, Debug, Eq, PartialEq, Sequence)]
pub struct CkksRotationDescriptorV1 {
    pub generator_version: u32,
    pub param_set: u32,
    pub param_hash: OctetString,
    pub old_descriptor_hash: OctetString,
    pub new_descriptor_hash: OctetString,
    pub old_lineage: OctetString,
    pub new_lineage: OctetString,
    pub key_id: OctetString,
    pub a_seed: OctetString,
    pub digits: u32,
    pub limbs: u32,
}

#[derive(Clone, Debug, Eq, PartialEq, Sequence)]
pub struct CkksRotationManifestTbsV1 {
    pub version: u32,
    pub rotation_descriptor_hash: OctetString,
    pub old_descriptor_hash: OctetString,
    pub new_descriptor_hash: OctetString,
    pub param_hash: OctetString,
    pub old_lineage: OctetString,
    pub new_lineage: OctetString,
    pub entries: Vec<CkksChunkHash>,
}

#[derive(Clone, Debug, Eq, PartialEq, Sequence)]
pub struct CkksSignedRotationManifestV1 {
    pub tbs: CkksRotationManifestTbsV1,
    pub signature: OctetString,
    pub signer_chain: Vec<Certificate>,
}

pub fn rotation_manifest_signed_bytes(tbs: &CkksRotationManifestTbsV1) -> Result<Vec<u8>, u32> {
    let mut msg = ROTATION_MANIFEST_DOMAIN.to_vec();
    msg.push(0);
    msg.extend_from_slice(&asn1::to_der(tbs)?);
    Ok(msg)
}

/// Receiver side, as `mech::verify_ckks_manifest`: decode, validate the signer
/// chain for the receipt-signing purpose, verify the ML-DSA-65 signature.
pub fn verify_ckks_rotation_manifest(der: &[u8], trust: &crate::replication::pki::TrustInputs, now: u64) -> Result<(CkksRotationManifestTbsV1, [u8; 32]), u32> {
    use crate::replication::{oids::Purpose, pki};
    let m: CkksSignedRotationManifestV1 = asn1::decode_strict(der, tf::MAX_PUBLIC_OBJECT)?;
    let t = &m.tbs;
    if t.version != 1 || [&t.rotation_descriptor_hash, &t.old_descriptor_hash, &t.new_descriptor_hash].iter().any(|h| h.as_bytes().len() != 32) || t.entries.iter().any(|e| e.sha256.as_bytes().len() != 32) {
        return Err(CKR_SIGNATURE_INVALID);
    }
    let chain = pki::validate_chain(&m.signer_chain, Purpose::ReceiptSigning, trust, now, crate::replication::Profile::Educational).map_err(|_| CKR_SIGNATURE_INVALID)?;
    let pk = pki::mldsa65_public(&chain.leaf).map_err(|_| CKR_SIGNATURE_INVALID)?;
    if !crate::replication::mldsa65_verify(pk, &rotation_manifest_signed_bytes(&m.tbs)?, m.signature.as_bytes()) {
        return Err(CKR_SIGNATURE_INVALID);
    }
    Ok((m.tbs, chain.device_id))
}

struct Seeds {
    slot: u32,
    new: SeedObject,
    old: SeedObject,
    ps: &'static CkksParamSet,
}

fn lineage(so: &SeedObject) -> Result<&[u8], u32> {
    so.attrs.get(&CKA_PQCTODAY_FHE_LINEAGE_ID).map(|v| v.as_slice()).ok_or(CKR_DEVICE_ERROR)
}

fn ckks_param_set(so: &SeedObject) -> Result<&'static CkksParamSet, u32> {
    if so.attrs.get(&CKA_PQCTODAY_FHE_SCHEME).map(|v| v.as_slice()) != Some(fhe::FHE_SCHEME_CKKS.as_bytes()) {
        return Err(CKR_KEY_TYPE_INCONSISTENT);
    }
    crate::state::get_object_attr_u32_from(&so.attrs, CKA_PQCTODAY_FHE_PARAM_SET).and_then(params::find).ok_or(CKR_KEY_TYPE_INCONSISTENT)
}

/// The rotation record of a seed: (new lineage, state).
fn rotation_record(attrs: &crate::crypto::handlers::Attributes) -> Option<(&[u8], u8)> {
    let v = attrs.get(&CKA_PRIV_FHE_ROTATION)?;
    (v.len() == 33).then(|| (&v[..32], v[32]))
}

/// Every rule of the module comment, in order, before any generation.
fn rotation_seeds(session: u32, old_lineage: &[u8; 32], new_lineage: &[u8; 32]) -> Result<Seeds, u32> {
    let m = CKM_PQCTODAY_FHE_DERIVE_PUBLIC;
    // The SO check runs first, whatever the lineages.
    crate::replication::require_profile()?;
    crate::replication::require_so(session)?;
    if old_lineage == new_lineage {
        return Err(CKR_MECHANISM_PARAM_INVALID);
    }
    let (slot, new) = tf::so_seed_by_lineage(session, new_lineage, m)?;
    let (_, old) = tf::so_seed_by_lineage(session, old_lineage, m)?;
    let ps = ckks_param_set(&new)?;
    if ckks_param_set(&old)?.id != ps.id || new.attrs.get(&CKA_PQCTODAY_FHE_PARAM_HASH) != old.attrs.get(&CKA_PQCTODAY_FHE_PARAM_HASH) {
        return Err(CKR_KEY_TYPE_INCONSISTENT);
    }
    let refuse = |why: &'static str| {
        crate::replication::note_refusal(why);
        crate::replication::oplog_event("fhe_ckks_rotation_refused", slot, &[("reason", format!("\"{why}\""))]);
        CKR_KEY_FUNCTION_NOT_PERMITTED
    };
    let same_value = new.seed.iter().zip(old.seed.iter()).fold(0u8, |a, (x, y)| a | (x ^ y)) == 0;
    if same_value || lineage(&new)? == lineage(&old)? {
        return Err(refuse("same seed"));
    }
    let local = crate::state::read_bool_attr(&new.attrs, CKA_LOCAL);
    if !local || crate::state::get_object_attr_u32_from(&new.attrs, CKA_KEY_GEN_MECHANISM) != Some(CKM_PQCTODAY_FHE_KEY_GEN) {
        return Err(refuse("new seed not generated by this token"));
    }
    let policy = |so: &SeedObject| so.attrs.get(&CKA_PQCTODAY_FHE_DECRYPT_POLICY).and_then(|id| fhe::find_decrypt_policy(slot, id));
    match (policy(&new), policy(&old)) {
        (Some(pn), Some(po)) if pn.is_equal_or_stricter_than(&po) => {}
        _ => return Err(refuse("new decryption policy not equal or stricter")),
    }
    if rotation_record(&new.attrs).is_some() {
        return Err(refuse("new seed was rotated away from"));
    }
    if rotation_record(&old.attrs).is_some_and(|(target, _)| target != lineage(&new).unwrap_or(&[])) {
        return Err(refuse("old seed already rotates to another seed"));
    }
    Ok(Seeds { slot, new, old, ps })
}

fn set_rotation_record(session: u32, old: &SeedObject, new_lineage: &[u8], state: u8) -> Result<(), u32> {
    let mut v = new_lineage.to_vec();
    v.push(state);
    if old.attrs.get(&CKA_PRIV_FHE_ROTATION) == Some(&v) {
        return Ok(());
    }
    crate::state::commit_objects_atomically(session, Vec::new(), vec![(old.handle, vec![(CKA_PRIV_FHE_ROTATION, v)])])?;
    Ok(())
}

/// The rotation context of two checked seeds: both key-set descriptor hashes
/// and the rotation a-seed, with the two generators.
fn context(s: &Seeds) -> Result<(Generator, Generator, RotationCtx), u32> {
    let g_new = Generator::new(s.ps, &s.new.seed);
    let g_old = Generator::new(s.ps, &s.old.seed);
    let mut ctx = RotationCtx {
        old_descriptor_hash: crate::replication::sha256(&mech::keyset_descriptor_der(&s.old, s.ps, &g_old)?),
        new_descriptor_hash: crate::replication::sha256(&mech::keyset_descriptor_der(&s.new, s.ps, &g_new)?),
        a_seed: [0; 32],
    };
    ctx.a_seed = g_new.rotation_a_seed(&ctx);
    Ok((g_new, g_old, ctx))
}

/// `CKM_PQCTODAY_FHE_DERIVE_PUBLIC` parameter version 3 (module comment).
#[allow(clippy::too_many_arguments)]
pub fn derive_rotation(session: u32, old_lineage: &[u8; 32], new_lineage: &[u8; 32], kind: u32, k: u32, d: u32, from: usize, to: usize) -> Result<u32, u32> {
    let s = rotation_seeds(session, old_lineage, new_lineage)?;
    let (h_new, h_old) = (s.new.handle, s.old.handle);
    let key = s.ps.rotation_desc();
    match kind {
        PUBLIC_KIND_CKKS_DESCRIPTOR => {}
        PUBLIC_KIND_CKKS_MANIFEST => {
            if (k, d, from, to) != (0, 0, 0, 0) {
                return Err(CKR_MECHANISM_PARAM_INVALID);
            }
            return derive_rotation_manifest(session, &s);
        }
        PUBLIC_KIND_CKKS_EVK_CHUNK => {
            if k != 0 || d as usize >= key.dnum() || from >= to || to > key.limbs() {
                return Err(CKR_MECHANISM_PARAM_INVALID);
            }
            if (to - from).saturating_mul(s.ps.n() * 8) > tf::MAX_PUBLIC_OBJECT {
                return Err(CKR_DEVICE_MEMORY);
            }
            if !mech::ledgers().get(&session).is_some_and(|l| l.seed_handle == h_new && l.old_seed == Some(h_old)) {
                return Err(CKR_OPERATION_NOT_INITIALIZED);
            }
        }
        _ => return Err(CKR_MECHANISM_PARAM_INVALID),
    }
    let (g_new, g_old, ctx) = context(&s)?;
    let new_lineage = lineage(&s.new)?.to_vec();
    let value = if kind == PUBLIC_KIND_CKKS_DESCRIPTOR {
        asn1::to_der(&CkksRotationDescriptorV1 {
            generator_version: params::GENERATOR_VERSION,
            param_set: s.ps.id,
            param_hash: asn1::octets(s.new.attrs.get(&CKA_PQCTODAY_FHE_PARAM_HASH).ok_or(CKR_DEVICE_ERROR)?),
            old_descriptor_hash: asn1::octets(&ctx.old_descriptor_hash),
            new_descriptor_hash: asn1::octets(&ctx.new_descriptor_hash),
            old_lineage: asn1::octets(lineage(&s.old)?),
            new_lineage: asn1::octets(&new_lineage),
            key_id: asn1::octets(&params::key_id(&key)),
            a_seed: asn1::octets(&ctx.a_seed),
            digits: key.dnum() as u32,
            limbs: key.limbs() as u32,
        })?
    } else {
        g_new.rotation_chunk(&g_old, &ctx, d, from, to).map_err(|_| CKR_MECHANISM_PARAM_INVALID)?
    };
    drop((g_new, g_old));
    {
        let mut l = mech::ledgers();
        let hash = crate::replication::sha256(&value);
        if kind == PUBLIC_KIND_CKKS_DESCRIPTOR {
            l.insert(session, Ledger { slot: s.slot, seed_handle: h_new, old_seed: Some(h_old), descriptor_hash: hash, entries: BTreeMap::new(), invalid: false });
        } else {
            let led = l.get_mut(&session).filter(|x| x.seed_handle == h_new && x.old_seed == Some(h_old)).ok_or(CKR_OPERATION_NOT_INITIALIZED)?;
            led.record(kind, 0, d, from as u32, to as u32, hash);
        }
    }
    if kind == PUBLIC_KIND_CKKS_DESCRIPTOR {
        // Recorded before any key byte leaves: the old seed now rotates to
        // this new seed only (a signed record stays signed).
        if rotation_record(&s.old.attrs).is_none() {
            set_rotation_record(session, &s.old, &new_lineage, ROTATION_STARTED)?;
        }
        crate::replication::oplog_event(
            "fhe_ckks_rotation_started",
            s.slot,
            &[("old_lineage", crate::replication::hex(lineage(&s.old)?)), ("new_lineage", crate::replication::hex(&new_lineage))],
        );
    }
    mech::public_object(session, &s.new, kind, value)
}

/// Kind 6 (version 3): sign the rotation ledger if it covers every digit
/// exactly once; then mark the old seed as rotated and clear the ledger.
fn derive_rotation_manifest(session: u32, s: &Seeds) -> Result<u32, u32> {
    let refuse = |why: &str| {
        crate::replication::oplog_event("fhe_ckks_manifest_refused", s.slot, &[("reason", format!("\"{why}\""))]);
        CKR_FUNCTION_FAILED
    };
    let (rot_hash, entries) = {
        let l = mech::ledgers();
        let led = l.get(&session).filter(|x| x.seed_handle == s.new.handle && x.old_seed == Some(s.old.handle)).ok_or(CKR_OPERATION_NOT_INITIALIZED)?;
        if led.invalid {
            return Err(refuse("overlapping or conflicting chunk"));
        }
        if !led.covers_rotation(s.ps) {
            return Err(refuse("incomplete coverage"));
        }
        let entries: Vec<CkksChunkHash> =
            led.entries.iter().map(|(&(kind, key, digit, from), &(to, h))| CkksChunkHash { kind, key, digit, from, to, sha256: asn1::octets(&h) }).collect();
        (led.descriptor_hash, entries)
    };
    let (_, _, ctx) = context(s)?;
    let new_lineage = lineage(&s.new)?.to_vec();
    let tbs = CkksRotationManifestTbsV1 {
        version: 1,
        rotation_descriptor_hash: asn1::octets(&rot_hash),
        old_descriptor_hash: asn1::octets(&ctx.old_descriptor_hash),
        new_descriptor_hash: asn1::octets(&ctx.new_descriptor_hash),
        param_hash: asn1::octets(s.new.attrs.get(&CKA_PQCTODAY_FHE_PARAM_HASH).ok_or(CKR_DEVICE_ERROR)?),
        old_lineage: asn1::octets(lineage(&s.old)?),
        new_lineage: asn1::octets(&new_lineage),
        entries,
    };
    let (sig, chain) = tf::receipt_sign(s.slot, &rotation_manifest_signed_bytes(&tbs)?)?;
    let value = asn1::to_der(&CkksSignedRotationManifestV1 { tbs, signature: asn1::octets(&sig), signer_chain: chain })?;
    if value.len() > tf::MAX_PUBLIC_OBJECT {
        return Err(CKR_DEVICE_MEMORY);
    }
    let h = mech::public_object(session, &s.new, PUBLIC_KIND_CKKS_MANIFEST, value)?;
    set_rotation_record(session, &s.old, &new_lineage, ROTATION_SIGNED)?;
    let mut l = mech::ledgers();
    if l.get(&session).is_some_and(|x| x.seed_handle == s.new.handle && x.old_seed == Some(s.old.handle) && x.descriptor_hash == rot_hash) {
        l.remove(&session);
    }
    drop(l);
    crate::replication::oplog_event(
        "fhe_ckks_rotation_manifest",
        s.slot,
        &[("old_lineage", crate::replication::hex(lineage(&s.old)?)), ("new_lineage", crate::replication::hex(&new_lineage))],
    );
    Ok(h)
}

/// Retire the old seed of a signed rotation (SO, R/W): destroy it, clear the
/// generator cache and every ledger that names it, and log both lineages.
/// `CKR_KEY_HANDLE_INVALID` when the lineage names no seed (or more than one),
/// `CKR_ACTION_PROHIBITED` unless the seed's rotation manifest was signed.
pub fn retire_old_seed(so_session: u32, old_lineage: &[u8; 32]) -> Result<(), u32> {
    let (slot, old) = tf::so_seed_by_lineage(so_session, old_lineage, CKM_PQCTODAY_FHE_DERIVE_PUBLIC)?;
    let new_lineage = match rotation_record(&old.attrs) {
        Some((target, ROTATION_SIGNED)) => target.to_vec(),
        _ => {
            crate::replication::oplog_event("fhe_ckks_rotation_refused", slot, &[("reason", "\"retire before a signed rotation manifest\"".into())]);
            return Err(CKR_ACTION_PROHIBITED);
        }
    };
    if old.attrs.get(&CKA_DESTROYABLE).is_some_and(|v| v.first() == Some(&0)) {
        return Err(CKR_ACTION_PROHIBITED);
    }
    mech::clear_generator_cache_for(old.handle);
    crate::ffi::drop_key_caches();
    crate::replication::discard_object(old.handle);
    crate::replication::oplog_event(
        "fhe_ckks_rotation_old_seed_destroyed",
        slot,
        &[("old_lineage", crate::replication::hex(old_lineage)), ("new_lineage", crate::replication::hex(&new_lineage))],
    );
    Ok(())
}
