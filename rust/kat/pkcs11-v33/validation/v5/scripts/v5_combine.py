"""
V5 (PKCS#11 v3.3 composite work, 2026-10-21): merge v5_kem_check.py and
v5_sig_check.py outputs into results.json with a summary of counts.

Usage: python3 v5_combine.py <out dir> <fixture sha256>
"""
import json
import os
import sys

d, fx_sha = sys.argv[1], sys.argv[2]
kem = json.load(open(os.path.join(d, "v5_kem_results.json")))
sig = json.load(open(os.path.join(d, "v5_sig_results.json")))


def count(rows, key):
    return f"{sum(1 for v in rows.values() if v.get(key) is True)}/{len(rows)}"


k, s = kem["results"], sig["results"]
out = {
    "input": {"fixture_sha256": fx_sha, "note": "self-generated by the pqctoday-hsm Rust engine; not upstream vectors"},
    "meta": {"kem_reference_VERSION_IMPLEMENTED": kem["reference_version_implemented"],
             "sig_reference_VERSION_IMPLEMENTED": sig["reference_version_implemented"]},
    "kem": k,
    "sig": s,
    "summary": {
        "kem_ref_decaps_matches_engine_k": count(k, "ref_decaps_matches_engine_k"),
        "kem_ref_pk_matches_engine_ek": count(k, "ref_pk_matches_engine_ek"),
        "kem_neg_tampered_ct_differs": count(k, "neg_tampered_trad_ct_differs"),
        "kem_ref_loader_as_shipped": count(k, "ref_loadKeyPair_as_shipped"),
        "sig_ref_verifies_s": count(s, "ref_verifies_s"),
        "sig_ref_verifies_sWithContext": count(s, "ref_verifies_sWithContext"),
        "sig_neg_sWithContext_without_ctx_rejected": count(s, "neg_sWithContext_without_ctx_rejected"),
        "sig_neg_s_with_ctx_rejected": count(s, "neg_s_with_ctx_rejected"),
        "sig_neg_other_message_rejected": count(s, "neg_other_message_rejected"),
    },
}
json.dump(out, open(os.path.join(d, "results.json"), "w"), indent=2)
print(json.dumps(out["summary"], indent=2))
