#!/usr/bin/env python3
"""Third-party notices for the engine release bundles.

Why: each engine tarball is a binary distribution of other people's code
(OpenSSL, SoftHSM2, strongSwan, OpenSSH, Emscripten's runtime, about a
hundred Rust crates). Their licences require the licence text and copyright
lines to travel with the binary, change notices for modified Apache-2.0
code, and for GPL code the licence text plus a pointer to the complete
source. This module produces, for every bundle in engines/bundles.json,
a THIRD-PARTY-NOTICES.txt and a LICENSES/ folder with the full texts.
scripts/publish_engines.py puts both into the bundle's tarball.

Inputs (all in this repository, so packaging needs no network and no cargo):
  engines/notices/components.json  non-Rust components, their licences and
                                   the files that hold the full texts
  engines/notices/texts/           licence texts copied from upstream sources
                                   that are not otherwise in this repository
  engines/notices/crates/<b>.json  Rust crates compiled into bundle <b>, with
                                   their licence texts; generated by the
                                   `crates` command below from Cargo.lock

The crate lists are generated where cargo and the crate sources are (the
project's Rust container), because the list must be the crates that are
really compiled for wasm32, not everything in Cargo.lock:

  python3 scripts/engine_notices.py crates          # in the Rust container (see local-gate.sh)
  python3 scripts/engine_notices.py check          # no cargo needed; CI runs this

`check` fails when a bundle declares no notices, a component or licence file
is missing, a crate has no licence, or a crate list was generated from a
different Cargo.lock than the one committed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUNDLES_FILE = os.path.join(ROOT, "engines", "bundles.json")
NOTICES_DIR = os.path.join(ROOT, "engines", "notices")
COMPONENTS_FILE = os.path.join(NOTICES_DIR, "components.json")
CRATES_DIR = os.path.join(NOTICES_DIR, "crates")
TARGET = "wasm32-unknown-unknown"
REPO_URL = "https://github.com/pqctoday-org/pqctoday-hsm"
LICENCE_FILE_RE = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE)([-_.].*)?$", re.IGNORECASE)


class NoticeError(Exception):
    pass


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_json(path: str) -> dict:
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def load_components(path: str = COMPONENTS_FILE) -> dict[str, dict]:
    doc = read_json(path)
    if doc.get("schema") != 1 or not isinstance(doc.get("components"), dict):
        raise NoticeError(f"{path}: not a schema 1 component list")
    return doc["components"]


def load_fallbacks(path: str = COMPONENTS_FILE) -> dict[str, dict]:
    """Crates that ship no licence file of their own, mapped to the crate whose texts apply."""
    return read_json(path).get("crateTextFallbacks", {})


def crate_texts(crate: dict, doc: dict, fallbacks: dict[str, dict]) -> list[dict]:
    """The licence files that apply to a crate: its own, or its declared fallback's."""
    if crate.get("files"):
        return crate["files"]
    fb = fallbacks.get(crate["name"])
    if not fb:
        return []
    for other in doc.get("crates", []):
        if other["name"] == fb["useTextsOf"] and other.get("files"):
            return other["files"]
    return []


def crates_file(bundle_name: str) -> str:
    return os.path.join(CRATES_DIR, f"{bundle_name}.json")


def lock_path(bundle: dict) -> str:
    """The Cargo.lock that governs a bundle's manifest (the workspace root's)."""
    manifest_dir = os.path.dirname(os.path.join(ROOT, bundle["cargoManifest"]))
    here = manifest_dir
    while True:
        candidate = os.path.join(here, "Cargo.lock")
        if os.path.isfile(candidate):
            return candidate
        if os.path.abspath(here) == ROOT:
            raise NoticeError(f"bundle {bundle['name']}: no Cargo.lock above {bundle['cargoManifest']}")
        here = os.path.dirname(here)


def file_sha256(path: str) -> str:
    with open(path, "rb") as handle:
        return sha256_bytes(handle.read())


# ---------------------------------------------------------------------------
# Generating the crate lists (needs cargo and the crate sources)


def cargo_metadata(manifest: str, online: bool = False) -> dict:
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked",
           "--filter-platform", TARGET, "--manifest-path", manifest]
    if not online:
        cmd.insert(4, "--offline")
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        raise NoticeError(f"cargo metadata failed for {manifest}:\n{proc.stderr[-2000:]}")
    return json.loads(proc.stdout)


def compiled_packages(meta: dict, manifest: str) -> list[dict]:
    """Packages reachable from the bundle's package through normal (not dev or build) edges."""
    manifest_abs = os.path.realpath(manifest)
    by_id = {p["id"]: p for p in meta["packages"]}
    roots = [p["id"] for p in meta["packages"] if os.path.realpath(p["manifest_path"]) == manifest_abs]
    if len(roots) != 1:
        raise NoticeError(f"{manifest}: expected exactly one package, found {len(roots)}")
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen: set[str] = set()
    todo = [roots[0]]
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k.get("kind") is None for k in dep.get("dep_kinds", [])):
                todo.append(dep["pkg"])
    return [by_id[pid] for pid in sorted(seen)]


def licence_files(package: dict) -> list[str]:
    pkg_dir = os.path.dirname(package["manifest_path"])
    names = [n for n in sorted(os.listdir(pkg_dir)) if LICENCE_FILE_RE.match(n) and os.path.isfile(os.path.join(pkg_dir, n))]
    extra = package.get("license_file")
    if extra and os.path.isfile(os.path.join(pkg_dir, extra)) and extra not in names:
        names.append(extra)
    return names


def build_crate_list(bundle: dict, online: bool = False) -> dict:
    manifest = os.path.join(ROOT, bundle["cargoManifest"])
    meta = cargo_metadata(manifest, online)
    root_real = os.path.realpath(ROOT)
    crates, texts = [], {}
    for pkg in compiled_packages(meta, manifest):
        pkg_dir = os.path.realpath(os.path.dirname(pkg["manifest_path"]))
        in_repo = pkg_dir.startswith(root_real + os.sep)
        rel_dir = os.path.relpath(pkg_dir, root_real) if in_repo else None
        files = []
        for name in licence_files(pkg):
            with open(os.path.join(pkg_dir, name), "rb") as handle:
                data = handle.read()
            digest = sha256_bytes(data)
            texts[digest] = data.decode("utf-8", errors="replace")
            files.append({"name": name, "sha256": digest})
        patches = None
        vendored = False
        if rel_dir:
            vendored = rel_dir.endswith("-patched") or "/vendor/" in f"/{rel_dir}/"
            for record in ("PATCHES.md", "PROVENANCE.md", f"../PROVENANCE-{pkg['name']}.md"):
                if os.path.isfile(os.path.join(pkg_dir, record)):
                    patches = os.path.normpath(f"{rel_dir}/{record}")
                    break
        crates.append({
            "name": pkg["name"],
            "version": pkg["version"],
            "license": pkg.get("license") or "",
            "repository": pkg.get("repository") or "",
            "source": "this repository" if in_repo else (pkg.get("source") or ""),
            "path": rel_dir,
            # A copy of someone else's crate kept in this repository ships its own
            # licence file; PQC Today's own crates do not.
            "thirdParty": (not in_repo) or vendored or patches is not None or bool(files),
            "modifiedRecord": patches,
            "files": files,
        })
    crates.sort(key=lambda c: (c["name"], c["version"]))
    return {
        "schema": 1,
        "bundle": bundle["name"],
        "cargoManifest": bundle["cargoManifest"],
        "target": TARGET,
        "cargoLock": os.path.relpath(lock_path(bundle), ROOT),
        "cargoLockSha256": file_sha256(lock_path(bundle)),
        "crates": crates,
        "texts": dict(sorted(texts.items())),
    }


def cmd_crates(args) -> int:
    bundles = [b for b in load_bundles() if b.get("cargoManifest")]
    if args.only:
        bundles = [b for b in bundles if b["name"] in args.only]
    os.makedirs(CRATES_DIR, exist_ok=True)
    for bundle in bundles:
        doc = build_crate_list(bundle, args.online)
        text = json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n"
        with open(crates_file(bundle["name"]), "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"  {bundle['name']}: {len(doc['crates'])} crates, {len(doc['texts'])} distinct licence texts")
    return 0


# ---------------------------------------------------------------------------
# Checking and rendering (no cargo needed)


def load_bundles(path: str = BUNDLES_FILE) -> list[dict]:
    return read_json(path)["bundles"]


def check_bundle(bundle: dict, components: dict[str, dict], fallbacks: dict[str, dict] | None = None) -> list[str]:
    fallbacks = load_fallbacks() if fallbacks is None else fallbacks
    name = bundle["name"]
    problems = []
    ids = bundle.get("notices")
    if ids is None or (not ids and not bundle.get("cargoManifest")):
        problems.append(f"{name}: declares no third-party notices (bundles.json 'notices')")
        ids = ids or []
    for cid in ids:
        comp = components.get(cid)
        if comp is None:
            problems.append(f"{name}: unknown component {cid}")
            continue
        for key in ("name", "version", "license", "source"):
            if not comp.get(key):
                problems.append(f"component {cid}: missing {key}")
        if not comp.get("licenseFiles"):
            problems.append(f"component {cid}: no licence files")
        for rel in comp.get("licenseFiles", []):
            full = os.path.join(ROOT, rel)
            if not os.path.isfile(full) or os.path.getsize(full) == 0:
                problems.append(f"component {cid}: licence file {rel} missing or empty")
    if bundle.get("cargoManifest"):
        path = crates_file(name)
        if not os.path.isfile(path):
            problems.append(f"{name}: no crate list {os.path.relpath(path, ROOT)}; run `scripts/engine_notices.py crates` in the Rust container")
            return problems
        doc = read_json(path)
        try:
            current = file_sha256(lock_path(bundle))
        except NoticeError as exc:
            problems.append(str(exc))
            current = None
        if current and doc.get("cargoLockSha256") != current:
            problems.append(f"{name}: crate list was generated from a different {doc.get('cargoLock')}; regenerate it")
        for crate in doc.get("crates", []):
            label = f"{name}: crate {crate['name']} {crate['version']}"
            if not crate.get("thirdParty"):
                continue  # PQC Today's own crates: covered by the repository licence
            if crate.get("source") == "this repository" and not crate.get("modifiedRecord"):
                problems.append(f"{label} is a changed third-party copy with no PATCHES.md or PROVENANCE.md")
            if not crate.get("license"):
                problems.append(f"{label} declares no licence")
            files = crate_texts(crate, doc, fallbacks)
            if not files:
                problems.append(f"{label} ships no licence file and has no crateTextFallbacks entry")
            for f in files:
                if f["sha256"] not in doc.get("texts", {}):
                    problems.append(f"{label}: text of {f['name']} missing from the crate list")
    return problems


def check_all() -> list[str]:
    components = load_components()
    problems = []
    for bundle in load_bundles():
        problems.extend(check_bundle(bundle, components))
    return problems


def cmd_check(_args) -> int:
    problems = check_all()
    if problems:
        print(f"engine notices: {len(problems)} problem(s)")
        for line in problems:
            print(f"  {line}")
        return 1
    print(f"engine notices: all {len(load_bundles())} bundle(s) have complete notices")
    return 0


def notices_prefix(bundle_name: str) -> str:
    return f"public/licenses/engines/{bundle_name}/"


def _wrap(label: str, value: str) -> str:
    return f"  {label:<10} {value}\n"


def render_bundle(bundle: dict, commit: str, components: dict[str, dict] | None = None) -> dict[str, bytes]:
    """Return {consumer-relative path: bytes} for the bundle's notices and licence texts."""
    components = components if components is not None else load_components()
    fallbacks = load_fallbacks()
    problems = check_bundle(bundle, components, fallbacks)
    if problems:
        raise NoticeError("; ".join(problems))
    name = bundle["name"]
    prefix = notices_prefix(name)
    out: dict[str, bytes] = {}
    seen_text: dict[str, str] = {}

    def add_text(rel_dir: str, file_name: str, data: bytes) -> str:
        digest = sha256_bytes(data)
        if digest in seen_text:
            return seen_text[digest]
        rel = f"LICENSES/{rel_dir}/{file_name}"
        out[prefix + rel] = data
        seen_text[digest] = rel
        return rel

    lines = [
        f"Third-party notices for the {name} engine bundle\n",
        "=" * 60 + "\n\n",
        f"Built from {REPO_URL} at commit {commit}\n",
        f"(source: {REPO_URL}/tree/{commit}).\n",
        "Code written by PQC Today, LLC is under the licence in that repository.\n",
        "This file lists the third-party code compiled into the bundle, its\n",
        "licence and where its full licence text is (LICENSES/ next to this file).\n\n",
    ]
    lines.append("Components\n----------\n\n")
    for cid in bundle["notices"]:
        comp = components[cid]
        lines.append(f"{comp['name']}\n")
        lines.append(_wrap("Version:", comp["version"]))
        lines.append(_wrap("Licence:", comp["license"]))
        for c in comp.get("copyright", []):
            lines.append(_wrap("Copyright:", c))
        lines.append(_wrap("Source:", comp["source"]))
        if comp.get("modified"):
            lines.append(_wrap("Changes:", comp["modified"]))
        if comp.get("sourceOffer"):
            lines.append(_wrap("Source:", comp["sourceOffer"].replace("{commit}", commit).replace("{repo}", REPO_URL)))
        for rel in comp["licenseFiles"]:
            with open(os.path.join(ROOT, rel), "rb") as handle:
                stored = add_text(cid, os.path.basename(rel), handle.read())
            lines.append(_wrap("Text:", stored))
        lines.append("\n")
    if bundle.get("cargoManifest"):
        doc = read_json(crates_file(name))
        crates = doc["crates"]
        own = [c for c in crates if not c.get("thirdParty")]
        third = [c for c in crates if c not in own]
        lines.append(f"Rust crates ({len(third)}, from {doc['cargoLock']}, target {doc['target']})\n")
        lines.append("-" * 40 + "\n\n")
        for crate in third:
            lines.append(f"{crate['name']} {crate['version']}\n")
            lines.append(_wrap("Licence:", crate["license"]))
            if crate.get("repository"):
                lines.append(_wrap("Source:", crate["repository"]))
            if crate.get("modifiedRecord"):
                lines.append(_wrap("Changes:", f"modified by PQC Today, LLC; see {crate['modifiedRecord']} at the commit above"))
            if not crate.get("files"):
                lines.append(_wrap("Note:", fallbacks[crate["name"]]["reason"]))
            for f in crate_texts(crate, doc, fallbacks):
                data = doc["texts"][f["sha256"]].encode("utf-8")
                stored = add_text(f"crates/{crate['name']}-{crate['version']}", f["name"], data)
                lines.append(_wrap("Text:", stored))
            lines.append("\n")
        if own:
            lines.append("Crates written by PQC Today, LLC (this repository): ")
            lines.append(", ".join(f"{c['name']} {c['version']}" for c in own) + "\n")
    out[prefix + "THIRD-PARTY-NOTICES.txt"] = "".join(lines).encode("utf-8")
    return dict(sorted(out.items()))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("crates", help="regenerate engines/notices/crates/*.json (needs cargo)")
    c.add_argument("--only", action="append", metavar="BUNDLE")
    c.add_argument("--online", action="store_true", help="let cargo download missing crate sources (CI)")
    sub.add_parser("check", help="check every bundle has complete notices (no cargo needed)")
    args = ap.parse_args(argv)
    try:
        return cmd_crates(args) if args.cmd == "crates" else cmd_check(args)
    except NoticeError as exc:
        print(f"engine notices: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
